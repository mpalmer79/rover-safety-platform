"""Programme review report renderers + bundle writer."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from app.programme_review.models import (
    DriftSeverity,
    PROGRAMME_CERTIFICATION_DISCLAIMER,
    ProgrammeReview,
    TrendCategory,
)


def write_programme_review_bundle(
    review: ProgrammeReview, *, out_dir: Path
) -> None:
    """Persist the documented set of programme-review artefacts."""

    out_dir.mkdir(parents=True, exist_ok=True)
    _write_json(out_dir / "index.json", _index_payload(review))
    _write_json(
        out_dir / "programme-health.json", review.governance_health.as_dict()
    )
    _write_json(out_dir / "trend-report.json", review.trend_report.as_dict())
    _write_json(out_dir / "drift-report.json", review.drift_report.as_dict())
    _write_json(
        out_dir / "subsystem-risk-report.json",
        review.subsystem_risk_report.as_dict(),
    )
    _write_json(
        out_dir / "governance-dashboard.json", _dashboard_payload(review)
    )
    _write_json(out_dir / "freshness-report.json", review.freshness_report.as_dict())
    _write_json(
        out_dir / "coverage-evolution.json", review.coverage_evolution.as_dict()
    )
    _write_json(out_dir / "gate-history.json", review.gate_history.as_dict())
    _write_json(out_dir / "programme-review.json", review.as_dict())

    (out_dir / "programme-review.md").write_text(
        render_programme_review_md(review), encoding="utf-8"
    )
    (out_dir / "programme-health.md").write_text(
        render_health_md(review), encoding="utf-8"
    )
    (out_dir / "trend-report.md").write_text(
        render_trend_md(review), encoding="utf-8"
    )
    (out_dir / "drift-report.md").write_text(
        render_drift_md(review), encoding="utf-8"
    )
    (out_dir / "subsystem-risk-report.md").write_text(
        render_subsystem_risk_md(review), encoding="utf-8"
    )
    (out_dir / "freshness-report.md").write_text(
        render_freshness_md(review), encoding="utf-8"
    )
    (out_dir / "coverage-evolution.md").write_text(
        render_coverage_evolution_md(review), encoding="utf-8"
    )
    (out_dir / "gate-history.md").write_text(
        render_gate_history_md(review), encoding="utf-8"
    )


# ---------------------------------------------------------------------------
# Index + dashboard payloads.
# ---------------------------------------------------------------------------


def _index_payload(review: ProgrammeReview) -> dict:
    return {
        "generated_at_utc": review.generated_at_utc,
        "fixture_mode": review.fixture_mode,
        "history_counts": dict(review.history_counts),
        "overall_health": review.governance_health.overall.value,
        "drift_severity": review.drift_report.severity.value,
        "gate_volatility": review.gate_history.volatility.value,
        "freshness_status_counts": review.freshness_report.status_counts(),
        "warnings": list(review.warnings),
    }


def _dashboard_payload(review: ProgrammeReview) -> dict:
    return {
        "generated_at_utc": review.generated_at_utc,
        "overall_health": review.governance_health.overall.value,
        "disciplines": [
            d.as_dict() for d in review.governance_health.disciplines
        ],
        "drift_severity": review.drift_report.severity.value,
        "trend_summary": [
            {
                "label": s.label,
                "category": s.category.value,
                "rolling_3": s.rolling_3.value,
                "rolling_5": s.rolling_5.value,
                "window_size": s.window_size,
            }
            for s in review.trend_report.series
        ],
        "gate_volatility": review.gate_history.volatility.value,
        "gate_sequence": list(review.gate_history.sequence),
        "coverage_evolution_origin_mix": review.coverage_evolution.origin_mix_label,
        "history_counts": dict(review.history_counts),
    }


# ---------------------------------------------------------------------------
# Markdown renderers.
