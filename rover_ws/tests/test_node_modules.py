"""Static-syntax validation for the Python node modules.

The full nodes import ``rclpy`` which is not present in this
environment, but we can still:

* parse them with :mod:`ast` to catch syntax regressions,
* ensure each declares a ``main()`` entry point listed in setup.py,
* ensure the safety bridge node references only allowed motion topics.
"""

from __future__ import annotations

import ast
from pathlib import Path

import pytest


_NODE_MODULES = {
    "rover_sensor_adapters": [
        "lidar_adapter.py",
        "imu_adapter.py",
        "odometry_adapter.py",
        "contact_adapter.py",
        "base_adapter.py",
    ],
    "rover_safety_bridge": [
        "safety_bridge_core.py",
        "safety_bridge_node.py",
    ],
    "rover_observability": [
        "run_manager.py",
        "event_recorder.py",
        "run_directory.py",
    ],
}


@pytest.mark.parametrize(
    "pkg,module",
    [
        (pkg, m)
        for pkg, modules in _NODE_MODULES.items()
        for m in modules
    ],
)
def test_node_module_parses(src_root: Path, pkg: str, module: str) -> None:
    path = src_root / pkg / pkg / module
    assert path.exists(), f"missing {path}"
    ast.parse(path.read_text(), filename=str(path))


def test_safety_bridge_node_only_publishes_authorized(src_root: Path) -> None:
    """Architectural invariant: only /cmd_vel_authorized is published.

    Parse the node source with :mod:`ast` and inspect every
    ``self.create_publisher`` call. The first positional argument
    after ``msg_type`` is the topic name; we assert no publisher
    targets ``/cmd_vel`` or ``/cmd_vel_requested``.
    """

    path = (
        src_root
        / "rover_safety_bridge"
        / "rover_safety_bridge"
        / "safety_bridge_node.py"
    )
    tree = ast.parse(path.read_text(), filename=str(path))
    forbidden = {"/cmd_vel", "/cmd_vel_requested"}
    saw_authorized_publisher = False
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        if not (
            isinstance(func, ast.Attribute) and func.attr == "create_publisher"
        ):
            continue
        # Topic name lives in either the second positional arg or the
        # name= keyword. We resolve both ast.Constant values and
        # ast.Name lookups to the module-level constants near the top.
        topic = _resolve_topic_arg(node, tree)
        if topic in forbidden:
            raise AssertionError(
                f"safety bridge publishes to forbidden topic {topic!r}"
            )
        if topic == "/cmd_vel_authorized":
            saw_authorized_publisher = True
    assert saw_authorized_publisher, "expected publisher for /cmd_vel_authorized"


def _resolve_topic_arg(call: ast.Call, tree: ast.Module) -> str | None:
    if len(call.args) >= 2:
        arg = call.args[1]
    else:
        return None
    if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
        return arg.value
    if isinstance(arg, ast.Name):
        # Look for ``NAME = "..."`` at module scope.
        for node in tree.body:
            if (
                isinstance(node, ast.Assign)
                and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)
                and node.targets[0].id == arg.id
                and isinstance(node.value, ast.Constant)
                and isinstance(node.value.value, str)
            ):
                return node.value.value
    return None


def test_safety_bridge_subscribes_to_requested(src_root: Path) -> None:
    text = (
        src_root
        / "rover_safety_bridge"
        / "rover_safety_bridge"
        / "safety_bridge_node.py"
    ).read_text()
    assert "/cmd_vel_requested" in text
    assert "create_subscription" in text


def test_setup_py_lists_console_scripts(src_root: Path) -> None:
    """Each ament_python package must declare its node entry points."""

    expected = {
        "rover_sensor_adapters": {
            "lidar_adapter",
            "imu_adapter",
            "odometry_adapter",
            "contact_adapter",
        },
        "rover_safety_bridge": {"safety_bridge_node"},
        "rover_observability": {"run_manager", "event_recorder"},
    }
    for pkg, names in expected.items():
        text = (src_root / pkg / "setup.py").read_text()
        for name in names:
            assert f"{name} = " in text, f"{pkg} missing entry point {name}"
